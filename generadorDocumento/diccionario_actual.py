def descripcion(tabla,columna,foreign=None):
    if columna=='expira_en':return 'Expiración de la sesión pública de Stripe.' if tabla=='transacciones_stripe' else 'Expiración de la sesión API vinculada al hash del token.'
    if tabla=='notificaciones' and columna=='tipo':return 'Asunto del correo manual, conservado en el historial.'
    if foreign:return 'Referencia a '+foreign+' que vincula este registro con su entidad relacionada.'
    if columna in CAMPO:return CAMPO[columna]
    if columna.startswith('nro_'):return 'Identificador de '+columna[4:].replace('_',' ')+' utilizado para identificar o vincular el registro.'
    if columna.endswith('_codigo'):return 'Código de '+columna[:-7].replace('_',' ')+' conservado para vincular la oferta o el recurso.'
    if columna.endswith('_correo'):return 'Correo identificador del '+columna[:-7].replace('_',' ')+' responsable o relacionado.'
    if columna in ('documento','rol','motivo_perdida'):return {'documento':'Identificador documental del prospecto.','rol':'Rol existente de la cuenta o de la matriz de permisos.','motivo_perdida':'Motivo clasificado de la oportunidad perdida.'}[columna]
    raise ValueError('Falta descripción semántica: '+tabla+'.'+columna)

def foreign_keys(data):
    out=[]
    for c in data['restricciones']:
        if c['tipo']!='f' or c['esquema']!='public':continue
        m=re.match(r'FOREIGN KEY \(([^)]+)\) REFERENCES (?:public\.)?(\w+)\(([^)]+)\)',c['definicion'])
        assert m,c
        out.append({'tabla':c['tabla'],'nombre':c['nombre'],'columnas':[x.strip() for x in m[1].split(',')],'destino':m[2],'destino_columnas':[x.strip() for x in m[3].split(',')],'definicion':c['definicion']})
    return out
